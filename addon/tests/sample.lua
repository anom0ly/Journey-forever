-- Serialise like the game: keys in brackets, arrays with index comments.
local out = {}
local function Key(k)
    return type(k) == "number" and ("[%d]"):format(k) or ("[%q]"):format(k)
end
local function Value(v)
    if type(v) == "string" then return ("%q"):format(v):gsub("\\\n", "\\n") end
    return tostring(v)
end
local function Dump(t, indent)
    local keys = {}
    for k in pairs(t) do keys[#keys + 1] = k end
    table.sort(keys, function(a, b)
        if type(a) == type(b) then return a < b end
        return type(a) == "number"
    end)
    local isArray = #t > 0
    for _, k in ipairs(keys) do
        local v = t[k]
        local prefix = indent .. (isArray and type(k) == "number" and "" or (Key(k) .. " = "))
        local suffix = isArray and type(k) == "number" and (", -- [%d]"):format(k) or ","
        if type(v) == "table" then
            out[#out + 1] = prefix .. "{"
            Dump(v, indent .. "\t")
            out[#out + 1] = indent .. "}" .. suffix
        else
            out[#out + 1] = prefix .. Value(v) .. suffix
        end
    end
end

JourneyForeverDB.run = nil
out[#out + 1] = "-- Sample JourneyForever.lua (made up, generated by addon/tests/sample.lua)"
out[#out + 1] = "JourneyForeverDB = {"
